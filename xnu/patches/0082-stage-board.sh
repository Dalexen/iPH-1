#!/bin/bash
# dxb runs patches/*.sh from the XNU source root before applying *.patch.
# Writes osfmk/arm64/sweet_board.h, the per-board constants the 0082 patch uses.
#   SWEET_BOARD=sweet  Redmi Note 10 Pro (SM7150), the default
#   SWEET_BOARD=mata   Essential PH-1 (MSM8998)
set -euo pipefail

[[ "${MACHINE_CONFIG:-}" == SWEET ]] || exit 0

board=${SWEET_BOARD:-sweet}
case "$board" in
    sweet) fb=0x9c000000 w=1080 h=2400 blocks=1 drivers=1 ;;
    # mata: splash address from the msm8998 reference trees (unverified on a PH-1;
    # tools/mkadt.py --fb overrides it for the shim, this one is compiled in).
    # 1312*2560*4 spills past the 32MB block that holds the base: map two.
    # The sm7150 MMIO drivers (keys, touch, USB) would poke unmapped addresses.
    mata) fb=${SWEET_FB_PHYS:-0x9d400000} w=1312 h=2560 blocks=2 drivers=0 ;;
    *) echo "unknown SWEET_BOARD=$board (sweet|mata)" >&2; exit 1 ;;
esac

cat > osfmk/arm64/sweet_board.h <<HDR
/* Generated by xnu/patches/0082-stage-board.sh (SWEET_BOARD=$board). */
#ifndef _ARM64_SWEET_BOARD_H_
#define _ARM64_SWEET_BOARD_H_
#define SWEET_FB_PHYS       $fb
#define SWEET_FB_W          $w
#define SWEET_FB_H          $h
#define SWEET_FB_STRIDE     $((w * 4))
#define SWEET_FB_BLOCKS     $blocks
#define SWEET_SOC_DRIVERS   $drivers
#endif
HDR
